/**
 * Asset string in the pre-HF26 format, e.g. `'1.000 HIVE'` or `'1.234567 VESTS'`.
 */
export type LegacyAsset = string

/**
 * Price in the pre-HF26 format, e.g. `{ base: '1.000 HIVE', quote: '1.000 HBD' }`.
 */
export type LegacyPriceType = Price<LegacyAsset>

/**
 * Generic operation, e.g. a virtual operation or a generic operation as typed
 * by dhive. Included in `LegacyOperation` as a fallback so that dhive values
 * (whose operations are typed as the generic `Operation`) remain assignable to
 * `LegacyTransaction` and `LegacySignedTransaction`.
 */
export interface LegacyOperationBase {
  0: LegacyOperationName | LegacyVirtualOperationName
  1: { [key: string]: any }
}

